suite "serialize — deterministic order + gamut map":
  test "orderedRoles: primitive -> semantic -> component, name-sorted":
    let prims = [ThemeToken(name: "z", color: red),
                 ThemeToken(name: "a", color: blue)]
    let sems = [ThemeToken(name: "m", alias: "a")]
    let t = theme(prims, sems, []).get
    let roles = orderedRoles(t)
    check roles == @[("a", tlPrimitive), ("z", tlPrimitive),
        ("m", tlSemantic)]
  test "serializeTheme: prims carry own color, sems carry resolved + alias":
    let prims = [ThemeToken(name: "z", color: red),
                 ThemeToken(name: "a", color: blue)]
    let sems = [ThemeToken(name: "m", alias: "a")]
    let t = theme(prims, sems, []).get
    let s = serializeTheme(t).get
    check s.len == 3
    check s[0].role == "a" and s[0].layer == tlPrimitive and s[0].alias == ""
    check s[1].role == "z" and s[1].layer == tlPrimitive and s[1].alias == ""
    check s[2].role == "m" and s[2].layer == tlSemantic and s[2].alias == "a"
    # The semantic node resolves to its primitive's color (blue), gamut-mapped.
    check s[2].color == s[0].color
  test "serializeTheme is deterministic (same input -> identical seq)":
    let prims = [ThemeToken(name: "z", color: red),
                 ThemeToken(name: "a", color: blue)]
    let sems = [ThemeToken(name: "m", alias: "a")]
    let t = theme(prims, sems, []).get
    let s1 = serializeTheme(t).get
    let s2 = serializeTheme(t).get
    check s1 == s2
  test "serializeTheme ignores hash-table insertion order":
    # Same role set built in reverse insertion order -> same sorted output.
    let t1 = theme([ThemeToken(name: "z", color: red),
                    ThemeToken(name: "a", color: blue)], [], []).get
    let t2 = theme([ThemeToken(name: "a", color: blue),
                    ThemeToken(name: "z", color: red)], [], []).get
    check serializeTheme(t1).get == serializeTheme(t2).get
  test "genHeader: UniColor brand + format + target + schema":
    let h = genHeader("css")
    check "Generated by UniColor" in h
    check "format: css" in h
    check "target: oklch" in h
    check "schema: 0" in h
  test "genHeader reflects legacy srgb target":
    let h = genHeader("css", SerializeOpts(target: tagSrgb, legacySrgb: true))
    check "target: srgb" in h

